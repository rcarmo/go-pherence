// Packed GGUF Q4_0 x Q8_0 AVX2/F16C row dot.
// The two four-lane accumulators and final reduction match llama.cpp's
// AVX2 reduction order and dotQ4_0Q8_0Scalar exactly.

#include "textflag.h"

// func dotQ4_0Q8_0AVX2(raw []byte, y []q8_0Block, blocks int) float32
TEXT ·dotQ4_0Q8_0AVX2(SB), NOSPLIT, $0-56
	MOVQ raw_base+0(FP), SI
	MOVQ y_base+24(FP), DI
	MOVQ blocks+48(FP), CX

	VXORPS X0, X0, X0              // low-nibble lanes 0..3
	VXORPS X1, X1, X1              // high-nibble lanes 0..3

	MOVL $0x00080008, AX
	VMOVD AX, X15
	VPBROADCASTD X15, Y15          // sixteen int16 values of 8
	VPCMPEQW Y14, Y14, Y14
	VPSRLW $12, Y14, Y14           // sixteen int16 values of 0x000f

	TESTQ CX, CX
	JZ reduce

loop:
	// Convert the block's fp16 scale and multiply by the Q8_0 fp32 scale.
	MOVW (SI), AX
	VMOVD AX, X12
	VCVTPH2PS X12, X12
	VMULSS (DI), X12, X12
	VSHUFPS $0, X12, X12, X12

	// Expand 16 packed bytes to int16 and form low-nibble values in [-8,7].
	VPMOVZXBW 2(SI), Y2
	VPAND Y14, Y2, Y3
	VPSUBW Y15, Y3, Y3
	VPMOVSXBW 4(DI), Y4
	VPMADDWD Y4, Y3, Y5            // eight adjacent-pair sums
	VPHADDD Y5, Y5, Y5             // duplicated four-product sums per 128-bit lane
	VEXTRACTI128 $1, Y5, X6
	VMOVLHPS X6, X5, X5            // [sum0,sum1,sum2,sum3]
	VCVTDQ2PS X5, X5
	VFMADD231PS X12, X5, X0

	// High nibbles correspond to the upper 16 Q8 activation values.
	VPSRLW $4, Y2, Y3
	VPAND Y14, Y3, Y3
	VPSUBW Y15, Y3, Y3
	VPMOVSXBW 20(DI), Y4
	VPMADDWD Y4, Y3, Y5
	VPHADDD Y5, Y5, Y5
	VEXTRACTI128 $1, Y5, X6
	VMOVLHPS X6, X5, X5
	VCVTDQ2PS X5, X5
	VFMADD231PS X12, X5, X1

	ADDQ $18, SI
	ADDQ $36, DI
	DECQ CX
	JNZ loop

reduce:
	VADDPS X1, X0, X0              // r0..r3
	VPSRLDQ $8, X0, X2
	VADDPS X2, X0, X0              // [r0+r2,r1+r3,...]
	VHADDPS X0, X0, X0
	VMOVSS X0, ret+56(FP)
	VZEROUPPER
	RET

// func dotQ4_0Q8_0x4AVX2(raw []byte, rowBytes int, y []q8_0Block, blocks int, out *[4]float32)
// Packs two output rows into each YMM register while preserving 128-bit lane reductions.
TEXT ·dotQ4_0Q8_0x4AVX2(SB), NOSPLIT, $0-72
	MOVQ raw_base+0(FP), SI
	MOVQ rowBytes+24(FP), AX
	LEAQ (SI)(AX*1), BX
	LEAQ (BX)(AX*1), DX
	LEAQ (DX)(AX*1), R8
	MOVQ y_base+32(FP), DI
	MOVQ blocks+56(FP), CX
	VXORPS Y0, Y0, Y0
	VXORPS Y1, Y1, Y1
	VXORPS Y7, Y7, Y7
	VXORPS Y8, Y8, Y8
	MOVL $0x0f0f0f0f, AX
	VMOVD AX, X14
	VPBROADCASTD X14, Y14
	MOVL $0x08080808, AX
	VMOVD AX, X15
	VPBROADCASTD X15, Y15
	MOVL $0x00010001, AX
	VMOVD AX, X13
	VPBROADCASTD X13, Y13
x4pair_loop:
	VMOVDQU 4(DI), X9
	VINSERTI128 $1, X9, Y9, Y9
	VMOVDQU 20(DI), X10
	VINSERTI128 $1, X10, Y10, Y10
	MOVW (SI), AX
	VMOVD AX, X4
	VCVTPH2PS X4, X4
	VMULSS (DI), X4, X4
	VSHUFPS $0, X4, X4, X4
	MOVW (BX), AX
	VMOVD AX, X5
	VCVTPH2PS X5, X5
	VMULSS (DI), X5, X5
	VSHUFPS $0, X5, X5, X5
	VINSERTF128 $1, X5, Y4, Y4
	VMOVDQU 2(SI), X2
	VMOVDQU 2(BX), X3
	VINSERTI128 $1, X3, Y2, Y2
	VPAND Y14, Y2, Y3
	VPSUBB Y15, Y3, Y3
	VPSIGNB Y9, Y3, Y3
	VPABSB Y9, Y5
	VPMADDUBSW Y3, Y5, Y3
	VPMADDWD Y13, Y3, Y3
	VCVTDQ2PS Y3, Y3
	VFMADD231PS Y4, Y3, Y0
	VPSRLW $4, Y2, Y3
	VPAND Y14, Y3, Y3
	VPSUBB Y15, Y3, Y3
	VPSIGNB Y10, Y3, Y3
	VPABSB Y10, Y5
	VPMADDUBSW Y3, Y5, Y3
	VPMADDWD Y13, Y3, Y3
	VCVTDQ2PS Y3, Y3
	VFMADD231PS Y4, Y3, Y1
	MOVW (DX), AX
	VMOVD AX, X4
	VCVTPH2PS X4, X4
	VMULSS (DI), X4, X4
	VSHUFPS $0, X4, X4, X4
	MOVW (R8), AX
	VMOVD AX, X5
	VCVTPH2PS X5, X5
	VMULSS (DI), X5, X5
	VSHUFPS $0, X5, X5, X5
	VINSERTF128 $1, X5, Y4, Y4
	VMOVDQU 2(DX), X2
	VMOVDQU 2(R8), X3
	VINSERTI128 $1, X3, Y2, Y2
	VPAND Y14, Y2, Y3
	VPSUBB Y15, Y3, Y3
	VPSIGNB Y9, Y3, Y3
	VPABSB Y9, Y5
	VPMADDUBSW Y3, Y5, Y3
	VPMADDWD Y13, Y3, Y3
	VCVTDQ2PS Y3, Y3
	VFMADD231PS Y4, Y3, Y7
	VPSRLW $4, Y2, Y3
	VPAND Y14, Y3, Y3
	VPSUBB Y15, Y3, Y3
	VPSIGNB Y10, Y3, Y3
	VPABSB Y10, Y5
	VPMADDUBSW Y3, Y5, Y3
	VPMADDWD Y13, Y3, Y3
	VCVTDQ2PS Y3, Y3
	VFMADD231PS Y4, Y3, Y8
	ADDQ $18, SI
	ADDQ $18, BX
	ADDQ $18, DX
	ADDQ $18, R8
	ADDQ $36, DI
	DECQ CX
	JNZ x4pair_loop
	VADDPS Y1, Y0, Y0
	VEXTRACTF128 $1, Y0, X6
	VPSRLDQ $8, X0, X2
	VADDPS X2, X0, X0
	VHADDPS X0, X0, X0
	VPSRLDQ $8, X6, X2
	VADDPS X2, X6, X6
	VHADDPS X6, X6, X6
	VADDPS Y8, Y7, Y7
	VEXTRACTF128 $1, Y7, X5
	VPSRLDQ $8, X7, X2
	VADDPS X2, X7, X7
	VHADDPS X7, X7, X7
	VPSRLDQ $8, X5, X2
	VADDPS X2, X5, X5
	VHADDPS X5, X5, X5
	MOVQ out+64(FP), AX
	VMOVSS X0, 0(AX)
	VMOVSS X6, 4(AX)
	VMOVSS X7, 8(AX)
	VMOVSS X5, 12(AX)
	VZEROUPPER
	RET
