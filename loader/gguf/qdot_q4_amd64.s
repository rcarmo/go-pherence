// Packed GGUF Q4_0 x Q8_0 AVX2/F16C row dot.
// The two four-lane accumulators and final reduction match llama.cpp's
// AVX2 reduction order and dotQ4_0Q8_0Scalar exactly.

#include "textflag.h"

// func dotQ4_0Q8_0AVX2(raw []byte, y []q8_0Block, blocks int) float32
TEXT ·dotQ4_0Q8_0AVX2(SB), NOSPLIT, $0-56
	MOVQ raw_base+0(FP), SI
	MOVQ y_base+24(FP), DI
	MOVQ blocks+48(FP), CX

	VXORPS X0, X0, X0              // low-nibble lanes 0..3
	VXORPS X1, X1, X1              // high-nibble lanes 0..3

	MOVL $0x00080008, AX
	VMOVD AX, X15
	VPBROADCASTD X15, Y15          // sixteen int16 values of 8
	VPCMPEQW Y14, Y14, Y14
	VPSRLW $12, Y14, Y14           // sixteen int16 values of 0x000f

	TESTQ CX, CX
	JZ reduce

loop:
	// Convert the block's fp16 scale and multiply by the Q8_0 fp32 scale.
	MOVW (SI), AX
	VMOVD AX, X12
	VCVTPH2PS X12, X12
	VMULSS (DI), X12, X12
	VSHUFPS $0, X12, X12, X12

	// Expand 16 packed bytes to int16 and form low-nibble values in [-8,7].
	VPMOVZXBW 2(SI), Y2
	VPAND Y14, Y2, Y3
	VPSUBW Y15, Y3, Y3
	VPMOVSXBW 4(DI), Y4
	VPMADDWD Y4, Y3, Y5            // eight adjacent-pair sums
	VPHADDD Y5, Y5, Y5             // duplicated four-product sums per 128-bit lane
	VEXTRACTI128 $1, Y5, X6
	VMOVLHPS X6, X5, X5            // [sum0,sum1,sum2,sum3]
	VCVTDQ2PS X5, X5
	VFMADD231PS X12, X5, X0

	// High nibbles correspond to the upper 16 Q8 activation values.
	VPSRLW $4, Y2, Y3
	VPAND Y14, Y3, Y3
	VPSUBW Y15, Y3, Y3
	VPMOVSXBW 20(DI), Y4
	VPMADDWD Y4, Y3, Y5
	VPHADDD Y5, Y5, Y5
	VEXTRACTI128 $1, Y5, X6
	VMOVLHPS X6, X5, X5
	VCVTDQ2PS X5, X5
	VFMADD231PS X12, X5, X1

	ADDQ $18, SI
	ADDQ $36, DI
	DECQ CX
	JNZ loop

reduce:
	VADDPS X1, X0, X0              // r0..r3
	VPSRLDQ $8, X0, X2
	VADDPS X2, X0, X0              // [r0+r2,r1+r3,...]
	VHADDPS X0, X0, X0
	VMOVSS X0, ret+56(FP)
	VZEROUPPER
	RET

// func dotQ4_0Q8_0x4AVX2(raw []byte, rowBytes int, y []q8_0Block, blocks int, out *[4]float32)
// Processes four output rows while sharing both Q8_0 activation loads.
TEXT ·dotQ4_0Q8_0x4AVX2(SB), NOSPLIT, $0-72
	MOVQ raw_base+0(FP), SI
	MOVQ rowBytes+24(FP), AX
	LEAQ (SI)(AX*1), BX
	LEAQ (BX)(AX*1), DX
	LEAQ (DX)(AX*1), R8
	MOVQ y_base+32(FP), DI
	MOVQ blocks+56(FP), CX

	VXORPS X0, X0, X0
	VXORPS X1, X1, X1
	VXORPS X7, X7, X7
	VXORPS X8, X8, X8
	VXORPS X9, X9, X9
	VXORPS X10, X10, X10
	VXORPS X11, X11, X11
	VXORPS X13, X13, X13
	MOVL $0x00080008, AX
	VMOVD AX, X15
	VPBROADCASTD X15, Y15
	VPCMPEQW Y14, Y14, Y14
	VPSRLW $12, Y14, Y14

x4loop:
	VPMOVSXBW 4(DI), Y6
	VPMOVSXBW 20(DI), Y5

	MOVW (SI), AX
	VMOVD AX, X12
	VCVTPH2PS X12, X12
	VMULSS (DI), X12, X12
	VSHUFPS $0, X12, X12, X12
	VPMOVZXBW 2(SI), Y2
	VPAND Y14, Y2, Y3
	VPSUBW Y15, Y3, Y3
	VPMADDWD Y6, Y3, Y4
	VPHADDD Y4, Y4, Y4
	VEXTRACTI128 $1, Y4, X3
	VMOVLHPS X3, X4, X4
	VCVTDQ2PS X4, X4
	VFMADD231PS X12, X4, X0
	VPSRLW $4, Y2, Y3
	VPAND Y14, Y3, Y3
	VPSUBW Y15, Y3, Y3
	VPMADDWD Y5, Y3, Y4
	VPHADDD Y4, Y4, Y4
	VEXTRACTI128 $1, Y4, X3
	VMOVLHPS X3, X4, X4
	VCVTDQ2PS X4, X4
	VFMADD231PS X12, X4, X1

	MOVW (BX), AX
	VMOVD AX, X12
	VCVTPH2PS X12, X12
	VMULSS (DI), X12, X12
	VSHUFPS $0, X12, X12, X12
	VPMOVZXBW 2(BX), Y2
	VPAND Y14, Y2, Y3
	VPSUBW Y15, Y3, Y3
	VPMADDWD Y6, Y3, Y4
	VPHADDD Y4, Y4, Y4
	VEXTRACTI128 $1, Y4, X3
	VMOVLHPS X3, X4, X4
	VCVTDQ2PS X4, X4
	VFMADD231PS X12, X4, X7
	VPSRLW $4, Y2, Y3
	VPAND Y14, Y3, Y3
	VPSUBW Y15, Y3, Y3
	VPMADDWD Y5, Y3, Y4
	VPHADDD Y4, Y4, Y4
	VEXTRACTI128 $1, Y4, X3
	VMOVLHPS X3, X4, X4
	VCVTDQ2PS X4, X4
	VFMADD231PS X12, X4, X8

	MOVW (DX), AX
	VMOVD AX, X12
	VCVTPH2PS X12, X12
	VMULSS (DI), X12, X12
	VSHUFPS $0, X12, X12, X12
	VPMOVZXBW 2(DX), Y2
	VPAND Y14, Y2, Y3
	VPSUBW Y15, Y3, Y3
	VPMADDWD Y6, Y3, Y4
	VPHADDD Y4, Y4, Y4
	VEXTRACTI128 $1, Y4, X3
	VMOVLHPS X3, X4, X4
	VCVTDQ2PS X4, X4
	VFMADD231PS X12, X4, X9
	VPSRLW $4, Y2, Y3
	VPAND Y14, Y3, Y3
	VPSUBW Y15, Y3, Y3
	VPMADDWD Y5, Y3, Y4
	VPHADDD Y4, Y4, Y4
	VEXTRACTI128 $1, Y4, X3
	VMOVLHPS X3, X4, X4
	VCVTDQ2PS X4, X4
	VFMADD231PS X12, X4, X10

	MOVW (R8), AX
	VMOVD AX, X12
	VCVTPH2PS X12, X12
	VMULSS (DI), X12, X12
	VSHUFPS $0, X12, X12, X12
	VPMOVZXBW 2(R8), Y2
	VPAND Y14, Y2, Y3
	VPSUBW Y15, Y3, Y3
	VPMADDWD Y6, Y3, Y4
	VPHADDD Y4, Y4, Y4
	VEXTRACTI128 $1, Y4, X3
	VMOVLHPS X3, X4, X4
	VCVTDQ2PS X4, X4
	VFMADD231PS X12, X4, X11
	VPSRLW $4, Y2, Y3
	VPAND Y14, Y3, Y3
	VPSUBW Y15, Y3, Y3
	VPMADDWD Y5, Y3, Y4
	VPHADDD Y4, Y4, Y4
	VEXTRACTI128 $1, Y4, X3
	VMOVLHPS X3, X4, X4
	VCVTDQ2PS X4, X4
	VFMADD231PS X12, X4, X13

	ADDQ $18, SI
	ADDQ $18, BX
	ADDQ $18, DX
	ADDQ $18, R8
	ADDQ $36, DI
	DECQ CX
	JNZ x4loop

	VADDPS X1, X0, X0
	VPSRLDQ $8, X0, X2
	VADDPS X2, X0, X0
	VHADDPS X0, X0, X0
	VADDPS X8, X7, X7
	VPSRLDQ $8, X7, X2
	VADDPS X2, X7, X7
	VHADDPS X7, X7, X7
	VADDPS X10, X9, X9
	VPSRLDQ $8, X9, X2
	VADDPS X2, X9, X9
	VHADDPS X9, X9, X9
	VADDPS X13, X11, X11
	VPSRLDQ $8, X11, X2
	VADDPS X2, X11, X11
	VHADDPS X11, X11, X11
	MOVQ out+64(FP), AX
	VMOVSS X0, 0(AX)
	VMOVSS X7, 4(AX)
	VMOVSS X9, 8(AX)
	VMOVSS X11, 12(AX)
	VZEROUPPER
	RET
