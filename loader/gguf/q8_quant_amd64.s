//go:build amd64

#include "textflag.h"

// func quantizeQ8_0BlockAVX2(d *float32, qs *[32]int8, row *float32)
TEXT ·quantizeQ8_0BlockAVX2(SB), NOSPLIT, $0-24
	MOVQ d+0(FP), DI
	MOVQ qs+8(FP), DX
	MOVQ row+16(FP), SI

	MOVL $0x7fffffff, AX
	VMOVD AX, X15
	VPBROADCASTD X15, Y15
	MOVQ $-9223372036854775808, AX
	VMOVQ AX, X14
	VPBROADCASTQ X14, Y14
	MOVQ $0x3fe0000000000000, AX
	VMOVQ AX, X13
	VPBROADCASTQ X13, Y13
	MOVL $127, AX
	VMOVD AX, X12
	VPBROADCASTD X12, Y12
	MOVL $-128, AX
	VMOVD AX, X11
	VPBROADCASTD X11, Y11

	// Absolute maximum is order-independent for finite activations.
	VMOVUPS 0(SI), Y8
	VMOVUPS 32(SI), Y9
	VMOVUPS 64(SI), Y6
	VMOVUPS 96(SI), Y7
	VCMPPS $7, Y8, Y8, Y5
	VPAND Y5, Y8, Y8
	VCMPPS $7, Y9, Y9, Y5
	VPAND Y5, Y9, Y9
	VCMPPS $7, Y6, Y6, Y5
	VPAND Y5, Y6, Y6
	VCMPPS $7, Y7, Y7, Y5
	VPAND Y5, Y7, Y7
	VANDPS Y15, Y8, Y8
	VANDPS Y15, Y9, Y9
	VANDPS Y15, Y6, Y6
	VANDPS Y15, Y7, Y7
	VMAXPS Y9, Y8, Y8
	VMAXPS Y7, Y6, Y6
	VMAXPS Y6, Y8, Y8
	VEXTRACTF128 $1, Y8, X9
	VMAXPS X9, X8, X8
	VSHUFPS $0x4e, X8, X8, X9
	VMAXPS X9, X8, X8
	VSHUFPS $0xb1, X8, X8, X9
	VMAXPS X9, X8, X8

	// d = amax/127 and id = d == 0 ? 0 : 1/d.
	MOVL $0x42fe0000, AX
	VMOVD AX, X10
	VDIVSS X10, X8, X8
	VXORPS X10, X10, X10
	VUCOMISS X10, X8
	JE q8_zero_id
	MOVL $0x3f800000, AX
	VMOVD AX, X10
	VDIVSS X8, X10, X10
q8_have_id:
	VBROADCASTSS X10, Y10

	// Return the unrounded scale; the Go wrapper applies the retained half
	// package's tie-up FP16 conversion after quantisation.
	VMOVSS X8, (DI)

	VMOVUPS 0(SI), Y0
	VMOVUPS 32(SI), Y1
	VMOVUPS 64(SI), Y2
	VMOVUPS 96(SI), Y3
	VMULPS Y10, Y0, Y0
	VMULPS Y10, Y1, Y1
	VMULPS Y10, Y2, Y2
	VMULPS Y10, Y3, Y3

	// Preserve math.Round(float64(float32(v*id))) exactly. Conversion to
	// float64 makes the signed 0.5 addition exact throughout [-127,127].
	VEXTRACTF128 $1, Y0, X5
	VCVTPS2PD X0, Y6
	VCVTPS2PD X5, Y7
	VPAND Y14, Y6, Y4
	VPOR Y13, Y4, Y4
	VADDPD Y4, Y6, Y6
	VPAND Y14, Y7, Y4
	VPOR Y13, Y4, Y4
	VADDPD Y4, Y7, Y7
	VCVTTPD2DQY Y6, X6
	VCVTTPD2DQY Y7, X7
	VINSERTI128 $1, X7, Y6, Y0
	VPMINSD Y12, Y0, Y0
	VPMAXSD Y11, Y0, Y0

	VEXTRACTF128 $1, Y1, X5
	VCVTPS2PD X1, Y6
	VCVTPS2PD X5, Y7
	VPAND Y14, Y6, Y4
	VPOR Y13, Y4, Y4
	VADDPD Y4, Y6, Y6
	VPAND Y14, Y7, Y4
	VPOR Y13, Y4, Y4
	VADDPD Y4, Y7, Y7
	VCVTTPD2DQY Y6, X6
	VCVTTPD2DQY Y7, X7
	VINSERTI128 $1, X7, Y6, Y1
	VPMINSD Y12, Y1, Y1
	VPMAXSD Y11, Y1, Y1

	VEXTRACTF128 $1, Y2, X5
	VCVTPS2PD X2, Y6
	VCVTPS2PD X5, Y7
	VPAND Y14, Y6, Y4
	VPOR Y13, Y4, Y4
	VADDPD Y4, Y6, Y6
	VPAND Y14, Y7, Y4
	VPOR Y13, Y4, Y4
	VADDPD Y4, Y7, Y7
	VCVTTPD2DQY Y6, X6
	VCVTTPD2DQY Y7, X7
	VINSERTI128 $1, X7, Y6, Y2
	VPMINSD Y12, Y2, Y2
	VPMAXSD Y11, Y2, Y2

	VEXTRACTF128 $1, Y3, X5
	VCVTPS2PD X3, Y6
	VCVTPS2PD X5, Y7
	VPAND Y14, Y6, Y4
	VPOR Y13, Y4, Y4
	VADDPD Y4, Y6, Y6
	VPAND Y14, Y7, Y4
	VPOR Y13, Y4, Y4
	VADDPD Y4, Y7, Y7
	VCVTTPD2DQY Y6, X6
	VCVTTPD2DQY Y7, X7
	VINSERTI128 $1, X7, Y6, Y3
	VPMINSD Y12, Y3, Y3
	VPMAXSD Y11, Y3, Y3

	// Saturating packs preserve token order and replace 32 scalar stores.
	VEXTRACTI128 $1, Y0, X4
	VPACKSSDW X4, X0, X0
	VEXTRACTI128 $1, Y1, X4
	VPACKSSDW X4, X1, X1
	VPACKSSWB X1, X0, X0
	VMOVDQU X0, 0(DX)
	VEXTRACTI128 $1, Y2, X4
	VPACKSSDW X4, X2, X2
	VEXTRACTI128 $1, Y3, X4
	VPACKSSDW X4, X3, X3
	VPACKSSWB X3, X2, X2
	VMOVDQU X2, 16(DX)
	VZEROUPPER
	RET

q8_zero_id:
	VXORPS X10, X10, X10
	JMP q8_have_id
